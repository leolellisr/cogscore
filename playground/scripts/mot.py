def mean_if_present(grouped, df: pd.DataFrame, column: str, output_name: str) -> Optional[pd.DataFrame]:
    if column not in df.columns:
        return None
    tmp = grouped[column].mean().reset_index().rename(columns={column: output_name})
    return tmp


def derive_summary_from_per_trial(per_trial: pd.DataFrame) -> pd.DataFrame:
    if per_trial.empty or not has_columns(per_trial, ["agent", "motivation_experiment_id", "episode"]):
        return pd.DataFrame()

    df = per_trial.copy()
    group_cols = ["agent", "motivation_experiment_id", "episode"]
    grouped = df.groupby(group_cols, dropna=False)
    frames: list[pd.DataFrame] = []

    metric_map = {
        "persistence_duration_cycles": "mean_persistence_duration_cycles",
        "persistence_selectivity": "mean_persistence_selectivity",
        "substitution_success": "substitution_success_rate",
        "perseveration": "mean_perseveration",
        "detour_efficiency": "mean_detour_efficiency",
        "inspection_coverage": "mean_inspection_coverage",
        "manipulation_coverage": "mean_manipulation_coverage",
        "first_attempt_accuracy": "first_attempt_accuracy_rate",
        "first_interaction_efficiency": "mean_first_interaction_efficiency",
        "devaluation_sensitivity": "mean_devaluation_sensitivity",
        "response_suppression": "mean_response_suppression",
        "raw_action_count": "raw_action_count",
        "motor_action_count": "mean_motor_action_count",
        "virtual_action_count": "mean_virtual_action_count",
        "attentional_action_count": "mean_attentional_action_count",
        "look_count": "look_count",
        "interaction_count": "interaction_count",
    }

    for source, dest in metric_map.items():
        tmp = mean_if_present(grouped, df, source, dest)
        if tmp is not None:
            frames.append(tmp)

    if "resource_choice" in df.columns:
        frames.append(grouped["resource_choice"].mean().reset_index().rename(columns={"resource_choice": "resource_choice_probability"}))
    if "novelty_choice" in df.columns:
        frames.append(grouped["novelty_choice"].mean().reset_index().rename(columns={"novelty_choice": "novelty_choice_probability"}))
    if "control_choice" in df.columns:
        frames.append(grouped["control_choice"].mean().reset_index().rename(columns={"control_choice": "control_choice_probability"}))

    if "first_functional_action" in df.columns:
        stop = df["first_functional_action"].astype(str).str.upper().eq("STOP").astype(float)
        tmp_df = df[group_cols].copy()
        tmp_df["omission_rate"] = stop
        frames.append(tmp_df.groupby(group_cols, dropna=False)["omission_rate"].mean().reset_index())

    if not frames:
        return pd.DataFrame()

    out = frames[0]
    for frame in frames[1:]:
        out = out.merge(frame, on=group_cols, how="outer")

    out = add_latent_learning_gains(out)
    out = add_behavioral_motivation_score(out)
    return out


def add_latent_learning_gains(summary: pd.DataFrame) -> pd.DataFrame:
    if summary.empty or "motivation_experiment_id" not in summary.columns:
        return summary

    out = summary.copy()
    if "latent_learning_gain_efficiency" not in out.columns:
        out["latent_learning_gain_efficiency"] = np.nan
    if "latent_learning_gain_latency" not in out.columns:
        out["latent_learning_gain_latency"] = np.nan

    # If the Java summary already computed explicit latent-learning gains, preserve them.
    if "condition" not in out.columns:
        return out

    # Optional condition-aware derivation for exp 4 when condition appears in summary rows.
    exp4 = out[pd.to_numeric(out["motivation_experiment_id"], errors="coerce") == 4].copy()
    if exp4.empty:
        return out

    if "mean_first_interaction_efficiency" in exp4.columns:
        pivot = exp4.pivot_table(
            index=["agent", "episode"],
            columns="condition",
            values="mean_first_interaction_efficiency",
            aggfunc="mean",
        )
        if "prior_exploration" in pivot.columns and "no_prior_exploration" in pivot.columns:
            gain = (pivot["prior_exploration"] - pivot["no_prior_exploration"]).reset_index(name="latent_learning_gain_efficiency")
            out = out.drop(columns=["latent_learning_gain_efficiency"], errors="ignore").merge(gain, on=["agent", "episode"], how="left")

    return out


def add_behavioral_motivation_score(summary: pd.DataFrame) -> pd.DataFrame:
    if summary.empty:
        return summary

    out = summary.copy()
    if "behavioral_motivation_score" in out.columns and out["behavioral_motivation_score"].notna().any():
        return out

    positive = [
        "mean_persistence_selectivity",
        "resource_modulation_index",
        "novelty_modulation_index",
        "substitution_success_rate",
        "mean_detour_efficiency",
        "mean_inspection_coverage",
        "mean_manipulation_coverage",
        "first_attempt_accuracy_rate",
        "mean_first_interaction_efficiency",
        "latent_learning_gain_efficiency",
        "mean_devaluation_sensitivity",
        "mean_response_suppression",
    ]
    negative = ["mean_perseveration", "omission_rate"]

    components: list[pd.Series] = []
    for col in positive:
        if col in out.columns:
            components.append(pd.to_numeric(out[col], errors="coerce").clip(0.0, 1.0))
    for col in negative:
        if col in out.columns:
            components.append(1.0 - pd.to_numeric(out[col], errors="coerce").clip(0.0, 1.0))

    if components:
        mat = pd.concat(components, axis=1)
        out["behavioral_motivation_score"] = mat.mean(axis=1, skipna=True)
    else:
        out["behavioral_motivation_score"] = np.nan

    return out


def combine_summary(summary: pd.DataFrame, derived: pd.DataFrame) -> pd.DataFrame:
    if summary.empty:
        return derived
    if derived.empty:
        return add_behavioral_motivation_score(summary)

    key_cols = ["agent", "motivation_experiment_id", "episode"]
    if not all(c in summary.columns for c in key_cols) or not all(c in derived.columns for c in key_cols):
        return add_behavioral_motivation_score(summary)

    out = summary.copy()
    for col in derived.columns:
        if col in key_cols:
            continue
        if col not in out.columns:
            out = out.merge(derived[key_cols + [col]], on=key_cols, how="outer")
        else:
            fill = derived[key_cols + [col]].rename(columns={col: f"__derived_{col}"})
            out = out.merge(fill, on=key_cols, how="left")
            out[col] = out[col].combine_first(out[f"__derived_{col}"])
            out = out.drop(columns=[f"__derived_{col}"])
    return add_behavioral_motivation_score(out)


