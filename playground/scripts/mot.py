def plot_metric_set(
    df: pd.DataFrame,
    metrics: list[str],
    out_dir: Path,
    show: bool,
    colors: dict[str, str],
    title: str,
    filename: str,
    ylabel: str,
    condition_cols: Optional[list[str]] = None,
    ylim: Optional[tuple[float, float]] = None,
    x_points: int = DEFAULT_X_POINTS,
    smooth_window: int = DEFAULT_SMOOTH_WINDOW,
    impute_zeros: bool = True,
    impute_lookback: int = DEFAULT_IMPUTE_LOOKBACK,
) -> None:
    condition_cols = condition_cols or []

    if not has_columns(df, ["agent", "motivation_experiment_id", "episode"]):
        return

    available_metrics = [m for m in metrics if m in df.columns]
    if not available_metrics:
        return

    missing_condition = [c for c in condition_cols if c not in df.columns]
    if missing_condition:
        return

    group_cols = ["agent", "motivation_experiment_id"] + condition_cols

    for exp_id, exp_df in df.groupby("motivation_experiment_id", dropna=False):
        try:
            exp_id_int = int(exp_id)
        except Exception:
            continue

        plt.figure(figsize=(12, 6))
        ax = plt.gca()
        any_line = False
        variant_counter = 0

        for metric in available_metrics:
            if metric not in exp_df.columns or exp_df[metric].dropna().empty:
                continue

            completed = complete_metric(
                exp_df,
                group_cols=group_cols,
                metric=metric,
                x_points=x_points,
                smooth_window=smooth_window,
                impute_zeros=impute_zeros,
                impute_lookback=impute_lookback,
            )
            if completed.empty:
                continue

            line_group_cols = ["agent"] + condition_cols
            for group_key, sub in completed.groupby(line_group_cols, dropna=False):
                if not isinstance(group_key, tuple):
                    group_key = (group_key,)

                agent = str(group_key[0])
                condition_values = group_key[1:]
                base_color = colors.get(agent, "black")

                condition_label = ""
                if condition_cols:
                    parts = [f"{metric_label(col)}={val}" for col, val in zip(condition_cols, condition_values)]
                    condition_label = " / " + ", ".join(parts)

                label = f"{agent} / {metric_label(metric)}{condition_label}"
                color = vary_color(base_color, variant_counter)
                linestyle = LINE_STYLES[variant_counter % len(LINE_STYLES)]
                marker = MARKERS[variant_counter % len(MARKERS)]

                sub = sub.sort_values("episode_axis")
                ax.plot(
                    sub["episode_axis"],
                    sub[f"{metric}_smooth"],
                    color=color,
                    linestyle=linestyle,
                    marker=marker,
                    markersize=3,
                    linewidth=2.1,
                    alpha=0.95,
                    label=label,
                )
                variant_counter += 1
                any_line = True

        if not any_line:
            plt.close()
            continue

        ax.set_title(f"{experiment_label(exp_id_int)} - {title}")
        ax.set_xlabel("Episode")
        ax.set_ylabel(ylabel)
        set_x_axis(ax, x_points)
        if ylim is not None:
            ax.set_ylim(*ylim)
        ax.grid(True, alpha=0.25)
        add_legend(ax, "Agent / metric / condition")
        save_plot(out_dir / f"exp{exp_id_int}_{filename}_x{x_points}_w{smooth_window}.png", show)


