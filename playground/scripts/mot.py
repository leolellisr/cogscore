def discover_agents(root: Path, benchmark_dir_name: str, only_agents: Optional[list[str]], flat_root: bool) -> list[tuple[str, Path]]:
    if flat_root:
        agent_name = root.name if root.name else "agent"
        return [(agent_name, root)] if root.exists() else []

    if not root.exists():
        return []

    agents: list[tuple[str, Path]] = []
    for child in sorted(root.iterdir()):
        if not child.is_dir():
            continue
        if only_agents and child.name not in only_agents:
            continue
        benchmark_dir = child / benchmark_dir_name
        if benchmark_dir.exists() and benchmark_dir.is_dir():
            agents.append((child.name, benchmark_dir))
    return agents


def read_agent_csvs(agent_name: str, benchmark_dir: Path, key: str) -> pd.DataFrame:
    paths: list[Path] = []
    for pattern in FILE_PATTERNS[key]:
        paths.extend(sorted(benchmark_dir.rglob(pattern)))
    paths = sorted(set(paths))

    frames: list[pd.DataFrame] = []
    for path in paths:
        try:
            df = pd.read_csv(path)
            df["agent"] = agent_name
            df["agent_dir"] = str(benchmark_dir)
            df["source_file"] = str(path)
            df["__source_row"] = range(len(df))
            frames.append(df)
        except Exception as exc:
            print(f"[WARN] Could not read {path}: {exc}", file=sys.stderr)

    if not frames:
        return pd.DataFrame()
    return pd.concat(frames, ignore_index=True, sort=False)


def load_all_agents(root: Path, benchmark_dir_name: str, only_agents: Optional[list[str]], flat_root: bool) -> dict[str, pd.DataFrame]:
    agents = discover_agents(root, benchmark_dir_name, only_agents, flat_root)

    print("[INFO] Agents discovered:")
    for agent_name, benchmark_dir in agents:
        print(f"  {agent_name}: {benchmark_dir}")

    if not agents:
        print(f"[WARN] No agents found under {root}", file=sys.stderr)

    loaded: dict[str, list[pd.DataFrame]] = {key: [] for key in FILE_PATTERNS}
    for agent_name, benchmark_dir in agents:
        for key in FILE_PATTERNS:
            df = read_agent_csvs(agent_name, benchmark_dir, key)
            if not df.empty:
                loaded[key].append(df)

    combined = {
        key: pd.concat(frames, ignore_index=True, sort=False) if frames else pd.DataFrame()
        for key, frames in loaded.items()
    }

    print("\n[INFO] Loaded rows:")
    for key, df in combined.items():
        print(f"  {key:10s}: {len(df)}")
    return combined


def normalize_common_columns(df: pd.DataFrame) -> pd.DataFrame:
    if df.empty:
        return df

    out = df.copy()
    out.columns = [str(c).strip() for c in out.columns]

    if "episode" not in out.columns and "epoch" in out.columns:
        out["episode"] = out["epoch"]
    if "episode" not in out.columns:
        out["episode"] = 0

    if "motivation_experiment_id" not in out.columns:
        for candidate in ["experiment_id", "active_motivation_experiment_id", "exp_id", "motivation_exp_id"]:
            if candidate in out.columns:
                out["motivation_experiment_id"] = out[candidate]
                break
    if "motivation_experiment_id" not in out.columns:
        out["motivation_experiment_id"] = np.nan

    if "trial_index" not in out.columns and "trial" in out.columns:
        out["trial_index"] = out["trial"]

    return out


def clean_frame(df: pd.DataFrame, episode: Optional[int], experiment: Optional[int]) -> pd.DataFrame:
    if df.empty:
        return df

    out = normalize_common_columns(df)

    for col in out.columns:
        if col in TEXT_COLUMNS or col.startswith("__"):
            continue
        converted = pd.to_numeric(out[col], errors="coerce")
        if converted.notna().sum() > 0:
            out[col] = converted

    if "agent" in out.columns:
        out["agent"] = out["agent"].astype(str)

    if episode is not None and "episode" in out.columns:
        out = out[pd.to_numeric(out["episode"], errors="coerce") == episode]

    if experiment is not None and "motivation_experiment_id" in out.columns:
        out = out[pd.to_numeric(out["motivation_experiment_id"], errors="coerce") == experiment]

    return out.copy()


def clean_data(data: dict[str, pd.DataFrame], episode: Optional[int], experiment: Optional[int]) -> dict[str, pd.DataFrame]:
    return {key: clean_frame(df, episode, experiment) for key, df in data.items()}


