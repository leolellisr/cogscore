def _sigmoid_progress(ep: int, n: int, midpoint: float = 0.35, steepness: float = 8.0) -> float:
    if n <= 1:
        return 1.0
    x = (ep - 1) / float(n - 1)
    raw = 1.0 / (1.0 + np.exp(-steepness * (x - midpoint)))
    lo = 1.0 / (1.0 + np.exp(-steepness * (0.0 - midpoint)))
    hi = 1.0 / (1.0 + np.exp(-steepness * (1.0 - midpoint)))
    return float((raw - lo) / (hi - lo))


def _lerp(start: float, end: float, p: float) -> float:
    return float(start + (end - start) * p)


def theoretical_summary_rows(x_points: int) -> list[dict]:
    rows: list[dict] = []

    for agent in ["Substage1_Theoretic", "Substage3_Theoretic"]:
        for exp_id in [1, 2, 3, 4, 5]:
            for ep in range(1, x_points + 1):
                p = _sigmoid_progress(ep, x_points)

                if agent == "Substage1_Theoretic":
                    # Reactive profile: stimulus-bound, weak drive modulation, weak flexibility.
                    persistence_duration = _lerp(1.0, 2.0, p)
                    persistence_selectivity = _lerp(0.15, 0.25, p)
                    resource_choice_prob = _lerp(0.30, 0.35, p)
                    novelty_choice_prob = _lerp(0.25, 0.30, p)
                    control_choice_prob = _lerp(0.25, 0.22, p)
                    resource_modulation = _lerp(0.05, 0.12, p)
                    novelty_modulation = _lerp(0.04, 0.10, p)
                    substitution_success = _lerp(0.05, 0.18, p)
                    perseveration = _lerp(0.80, 0.65, p)
                    detour_efficiency = _lerp(0.05, 0.20, p)
                    inspection_coverage = _lerp(0.20, 0.35, p)
                    manipulation_coverage = _lerp(0.10, 0.25, p)
                    first_attempt_accuracy = _lerp(0.18, 0.30, p)
                    first_interaction_efficiency = _lerp(0.08, 0.20, p)
                    latent_gain_eff = _lerp(0.00, 0.08, p)
                    latent_gain_lat = _lerp(0.00, 0.05, p)
                    devaluation_sensitivity = _lerp(0.05, 0.20, p)
                    response_suppression = _lerp(0.05, 0.18, p)
